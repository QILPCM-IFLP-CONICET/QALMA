"""Free energy of Gibbs states in the RPA, against the exact -ln Z."""

from functools import partial

import numpy as np
import pytest
import qutip

from qalma import build_system
from qalma.meanfield import compute_free_energy, symmetry_breaking_mfa
from qalma.meanfield.rpa import RPAGibbsDensityOperator
from qalma.operators.states import GibbsDensityOperator
from qalma.projections.symmetries import (
    project_conserved_quantity,
    project_parity_like,
)


def ising_chain(size, gamma):
    """Ising chain in a transverse field, -sum sz sz - gamma sum sx (Pauli units).

    The local operator ``ParityX`` (sigma^x) generates its spin-flip parity.
    """
    system = build_system("open chain lattice", "spin", L=size, J=1.0)
    system.spec["model"].site_basis["0"]["operators"]["ParityX"] = qutip.sigmax()
    sites = tuple(system.sites)
    sx = [system.site_operator(f"Sx@{s}") for s in sites]
    sz = [system.site_operator(f"Sz@{s}") for s in sites]
    ham = -sum(4 * sz[i] * sz[i + 1] for i in range(size - 1)) - 2 * gamma * sum(sx)
    return system, ham.simplify()


def fully_connected(size, field, jx=1.0, jy=0.5):
    """XY model with all-to-all couplings 2/N and a field along z."""
    system = build_system("chain lattice", "spin", L=size, J=1, local_S=0.5)
    names = list(system.sites)

    def op(name, site):
        return system.site_operator(f"{name}@{site}")

    ham = field * sum(op("Sz", s) for s in names)
    for i, a in enumerate(names):
        for b in names[i + 1 :]:
            ham = ham - (2.0 / size) * (
                jx * op("Sx", a) * op("Sx", b) + jy * op("Sy", a) * op("Sy", b)
            )
    return system, ham.simplify()


def exact_free_energy(k):
    """-ln Z, exact."""
    return float(np.real(GibbsDensityOperator(k).free_energy))


@pytest.mark.parametrize("beta", [0.1, 1.0, 4.0])
def test_normal_phase(beta):
    """Far from transitions, the RPA improves the mean field at all temperatures."""
    system, ham = ising_chain(6, 3.0)
    k = (beta * ham).simplify()
    exact = exact_free_energy(k)
    estimate = RPAGibbsDensityOperator(k, system).rpa_free_energy()
    assert estimate.broken == []
    assert estimate.symmetry == 0.0
    assert estimate.stability > 0.25
    err_mf = estimate.mean_field - exact
    err_rpa = estimate.total - exact
    assert abs(err_rpa) < 0.15 * abs(err_mf)
    if beta == 0.1:
        assert abs(err_rpa) < 1e-3


def test_terms_are_consistent():
    """The mean-field term is the variational free energy; total is the sum."""
    system, ham = ising_chain(5, 3.0)
    k = (1.0 * ham).simplify()
    state = RPAGibbsDensityOperator(k, system)
    estimate = state.rpa_free_energy()
    sigma = state.rpa_structure.sigma_mf
    assert estimate.mean_field == pytest.approx(
        float(np.real(compute_free_energy(sigma, state.rpa_structure.generator)))
    )
    assert estimate.total == pytest.approx(
        estimate.mean_field + estimate.dynamic + estimate.static + estimate.symmetry
    )
    assert estimate.dynamic < 0


@pytest.mark.parametrize("beta", [4.0, 8.0])
def test_broken_parity_is_restored(beta):
    """With the parity declared, its breaking adds -ln 2."""
    system, ham = ising_chain(6, 0.3)
    k = (beta * ham).simplify()
    exact = exact_free_energy(k)
    mf = symmetry_breaking_mfa(k, system, numfields=6, n_attempts=3, seed=0)
    parity = (partial(project_parity_like, op_name="ParityX"),)
    with_parity = RPAGibbsDensityOperator(
        k, system, meanfield=mf, symmetry_projections=parity
    ).rpa_free_energy()
    assert with_parity.broken == ["parity generated by ParityX"]
    assert with_parity.symmetry == pytest.approx(-np.log(2))
    assert abs(with_parity.total - exact) < 0.03
    assert with_parity.mean_field - exact > 0.6
    # Without declaring the symmetry, the error is ln 2.
    without = RPAGibbsDensityOperator(k, system, meanfield=mf).rpa_free_energy()
    assert without.total - exact == pytest.approx(np.log(2), abs=0.03)


def test_unbroken_symmetry_adds_nothing():
    """A declared symmetry that the mean field does not break adds no term."""
    system, ham = ising_chain(6, 0.3)
    k = (0.25 * ham).simplify()
    parity = (partial(project_parity_like, op_name="ParityX"),)
    estimate = RPAGibbsDensityOperator(
        k, system, symmetry_projections=parity
    ).rpa_free_energy()
    assert estimate.broken == []
    assert estimate.symmetry == 0.0


def test_fully_connected_normal_phase():
    """In the fully connected model the RPA is accurate in the normal phase."""
    system, ham = fully_connected(6, 1.5)
    for beta in (0.5, 4.0):
        k = (beta * ham).simplify()
        estimate = RPAGibbsDensityOperator(k, system).rpa_free_energy()
        assert abs(estimate.total - exact_free_energy(k)) < 0.01


def test_non_involution_and_unknown_projections_warn():
    """Projections that cannot be classified issue a warning and add nothing."""
    system, ham = ising_chain(4, 3.0)
    k = (1.0 * ham).simplify()
    for projections in (
        (partial(project_parity_like, op_name="Sx"),),
        (lambda state: state,),
    ):
        state = RPAGibbsDensityOperator(k, system, symmetry_projections=projections)
        with pytest.warns(UserWarning, match="Cannot decide"):
            estimate = state.rpa_free_energy()
        assert estimate.symmetry == 0.0


def u1_fisher_information(system, sigma):
    """Quantum Fisher information of a product state for the total Sz."""
    factors = sigma.site_factors_qutip
    total = 0.0
    for site in system.sites:
        q_loc = system.site_operator("Sz", site).to_qutip((site,)).full()
        rho = factors[site].full() if site in factors else np.eye(2) / 2
        probs, vecs = np.linalg.eigh(rho)
        matrix = vecs.conj().T @ q_loc @ vecs
        for a in range(2):
            for b in range(2):
                if probs[a] + probs[b] > 1e-14:
                    total += (
                        2
                        * (probs[a] - probs[b]) ** 2
                        / (probs[a] + probs[b])
                        * abs(matrix[a, b]) ** 2
                    )
    return total


def test_broken_u1_symmetry_orbit_term():
    """A broken U(1) removes the zero mode and adds the orbit of the mean field."""
    system, ham = fully_connected(8, 0.5, jx=1.0, jy=1.0)
    k = (4.0 * ham).simplify()
    exact = exact_free_energy(k)
    mf = symmetry_breaking_mfa(k, system, numfields=6, n_attempts=3, seed=0)
    u1 = (partial(project_conserved_quantity, op_name="Sz"),)
    state = RPAGibbsDensityOperator(k, system, meanfield=mf, symmetry_projections=u1)
    estimate = state.rpa_free_energy()
    assert estimate.broken == ["U(1) generated by Sz"]
    fisher = u1_fisher_information(system, state.rpa_structure.sigma_mf)
    expected = -np.log(max(1.0, np.sqrt(2 * np.pi * fisher / 4)))
    assert estimate.symmetry == pytest.approx(expected)
    assert estimate.stability > 0.25
    assert abs(estimate.total - exact) < 0.2 * (estimate.mean_field - exact)


@pytest.mark.parametrize("field,expected", [(20.0, "pure"), (0.01, "symmetric")])
def test_orbit_length_uses_the_fisher_information(field, expected):
    """The orbit term counts distinguishable states: zero for symmetric states."""
    from qalma.meanfield.rpa.free_energy import _orbit_term
    from qalma.operators.states import GibbsProductDensityOperator

    system, _ = fully_connected(8, 0.5, jx=1.0, jy=1.0)
    sx = sum(system.site_operator(f"Sx@{s}") for s in system.sites)
    sigma = GibbsProductDensityOperator((-field * sx).simplify())
    term = _orbit_term(sigma, system, "Sz")
    if expected == "pure":
        # nearly pure states along x: F_Q/4 = Var(Sz) = 1/4 per site
        assert term == pytest.approx(-0.5 * np.log(2 * np.pi * 8 / 4), abs=1e-6)
    else:
        # nearly symmetric states: Var(Sz) ~ 2, but the orbit is a single state
        assert term == 0.0


def test_zero_modes_require_a_declared_u1_symmetry():
    """Zero modes without a declared broken U(1) symmetry raise an error."""
    system, ham = fully_connected(6, 0.5, jx=1.0, jy=1.0)
    k = (4.0 * ham).simplify()
    mf = symmetry_breaking_mfa(k, system, numfields=6, n_attempts=3, seed=0)
    state = RPAGibbsDensityOperator(k, system, meanfield=mf)
    with pytest.raises(ValueError, match="zero mode"):
        state.rpa_free_energy()


def test_warning_close_to_an_instability():
    """Close to the transition of the mean field, a warning is issued."""
    system, ham = ising_chain(6, 0.3)
    k = (0.5 * ham).simplify()
    state = RPAGibbsDensityOperator(k, system)
    with pytest.warns(UserWarning, match="close to an instability"):
        estimate = state.rpa_free_energy()
    assert estimate.stability < 0.25


def test_free_energy_property_is_the_rpa_estimate():
    """The free_energy of an RPA state is the RPA estimate, and is read-only."""
    system, ham = ising_chain(5, 3.0)
    k = (1.0 * ham).simplify()
    state = RPAGibbsDensityOperator(k, system)
    assert state.free_energy == pytest.approx(state.rpa_free_energy().total)
    assert state.rpa_free_energy() is state.rpa_free_energy()  # cached
    with pytest.raises(AttributeError, match="cannot be set"):
        state.free_energy = 0.0


def test_estimate_does_not_depend_on_normalization():
    """Normalizing the state (K -> K + ln Z) does not change the estimate."""
    system, ham = ising_chain(5, 3.0)
    k = (1.0 * ham).simplify()
    reference = RPAGibbsDensityOperator(k, system).free_energy
    normalized = RPAGibbsDensityOperator(k, system)
    normalized.normalize()
    assert normalized.normalized
    assert normalized.free_energy == pytest.approx(reference, abs=1e-10)
    assert abs(reference - exact_free_energy(k)) < 0.1
