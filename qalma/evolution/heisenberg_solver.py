"""
Heisenberg solver.

Solve a truncated hierarchy of Heisenberg equations for a set of
observables.
"""

from datetime import datetime
from typing import Any, Callable, Dict, Iterable, Optional, cast

import numpy as np
from numpy.typing import NDArray

from qalma.operators import Operator
from qalma.operators.states import DensityOperatorProtocol
from qalma.scalarprod.basis import HierarchicalOperatorBasis, OperatorBasis
from qalma.scalarprod.build import fetch_covar_scalar_product

from .common import normalize_e_ops
from .simulation import Simulation

__all__ = ["heisenberg_solve"]


def heisenberg_solve(
    ham: Operator,
    rho0: DensityOperatorProtocol,
    t_span,
    *,
    e_ops: list[Operator] | dict[Any, Operator],
    order: int = 2,
    sp: Optional[Callable] = None,
) -> Simulation:
    """Solve the evolution of expectation values in the Heisenberg picture.

    The observables in ``e_ops`` are evolved in a hierarchical basis of
    depth ``order`` generated by each of them, and their expectation values
    are taken in ``rho0``.

    Parameters
    ----------
    ham : Operator
        The Hamiltonian.
    rho0 : DensityOperatorProtocol
        The initial state.
    t_span : array-like
        Output times.
    e_ops : dict or list of Operator
        The observables (required).
    order : int
        Depth of the hierarchical bases.
    sp : callable, optional
        Scalar product; by default, the covariance product of ``rho0``.

    Returns
    -------
    Simulation
        Without states (``parameters["states"] == "none"``); ``stats`` has
        ``"method"`` and ``"wall time"``.
    """
    start_time = datetime.now()
    if sp is None:
        sp = fetch_covar_scalar_product(rho0)
    if callable(e_ops) or e_ops is None:
        raise TypeError("heisenberg_solve needs e_ops as a dict or list of operators.")
    e_ops_dict = cast(Dict[Any, Operator], normalize_e_ops(e_ops))

    seeds: Iterable[Operator] = e_ops_dict.values()
    # Build a basis as a union of the hierarchical basis generated by each
    # operator.
    basis: OperatorBasis = cast(
        OperatorBasis,
        sum(HierarchicalOperatorBasis(seed, -ham, order, sp) for seed in seeds),
    )
    basis_expectation_values: NDArray = np.array(rho0.expect(basis.operator_basis))
    fields_0: NDArray = np.array([basis.coefficient_expansion(op) for op in seeds]).T
    result: list = []
    for t in t_span:
        phis = basis_expectation_values @ basis.evolve(t, fields_0)[0]
        result.append(phis)

    return Simulation(
        parameters={
            "method": "heisenberg",
            "system": ham.system,
            "states": "none",
            "order": order,
        },
        stats={
            "method": "heisenberg",
            "wall time": (datetime.now() - start_time).total_seconds(),
        },
        time_span=list(t_span),
        expect_ops=dict(zip(e_ops_dict.keys(), np.array(result).T)),
        states=[],
    )
